char toLowerAscii(char c) {
    return (c >= 'A' && c <= 'Z') ? static_cast<char>(c - 'A' + 'a') : c;
}

std::string lowerAscii(std::string_view s) {
    std::string out;
    out.reserve(s.size());
    for (char c : s) {
        out.push_back(toLowerAscii(c));
    }
    return out;
}

size_t countUtf8Codepoints(std::string_view s) {
    size_t n = 0;
    for (unsigned char c : s) {
        if ((c & 0xC0) != 0x80) {
            ++n;
        }
    }
    return n;
}

size_t countAsciiWords(std::string_view s) {
    size_t n = 0;
    bool in_word = false;
    for (unsigned char c : s) {
        const bool sep = (c == ' ' || c == '\t' || c == '\n' || c == '\r');
        if (!sep && !in_word) {
            in_word = true;
            ++n;
        } else if (sep) {
            in_word = false;
        }
    }
    return n;
}

void addZh(BuiltinDictIndex &idx, std::string_view zh, std::string_view en) {
    idx.zh_to_en.try_emplace(std::string(zh), std::string(en));
    idx.max_zh_cp = std::max(idx.max_zh_cp, countUtf8Codepoints(zh));
}

void addEn(BuiltinDictIndex &idx, std::string_view en, std::string_view zh) {
    std::string key = lowerAscii(en);
    idx.en_to_zh.try_emplace(key, std::string(zh));
    idx.max_en_words = std::max(idx.max_en_words, countAsciiWords(key));
}

void addPair(BuiltinDictIndex &idx, std::string_view zh, std::string_view en) {
    addZh(idx, zh, en);
    addEn(idx, en, zh);
}

